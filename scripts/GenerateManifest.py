#!/usr/bin/env python3
"""
Generate the SkillStack manifest.

Walks every theme folder, parses each SKILL.md's YAML frontmatter, and writes
the aggregated metadata to skills/skills.yaml. The manifest records the total
counts plus per-theme and per-skill entries carrying the canonical fields:
name, description, tags, related, prerequisites, outputs, difficulty,
estimated_tokens, permissions.

CLI:
  python scripts/GenerateManifest.py
  python scripts/GenerateManifest.py --check

With ``--check`` the script exits non-zero when the on-disk manifest is
stale relative to the parsed skills.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

# Ensure the scripts/ directory is importable when run as a script.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _SkillLib import EnsureDir, IterateSkills, SkillDoc, SkillsRoot


def BuildSkillEntry(doc: SkillDoc) -> dict:
  """
  Convert a parsed SkillDoc into a manifest skill entry.

  Args:
    doc (SkillDoc): The parsed skill document.

  Returns:
    dict: A mapping with the canonical skill fields.
  """
  # Compose the per-skill manifest entry using CamelCase dict keys.
  return {
    "Name": doc.Name,
    "Description": doc.Description,
    "Tags": list(doc.Tags),
    "Related": list(doc.Related),
    "Prerequisites": list(doc.Prerequisites),
    "Outputs": list(doc.Outputs),
    "Difficulty": doc.Difficulty,
    "EstimatedTokens": int(doc.EstimatedTokens),
    "Permissions": list(doc.Permissions),
  }


def BuildThemeEntry(themeName: str, docs: list[SkillDoc]) -> dict:
  """
  Convert a list of skills under one theme into a manifest theme entry.

  Args:
    themeName (str): The theme folder name.
    docs (list[SkillDoc]): Parsed skills belonging to the theme.

  Returns:
    dict: A mapping with the theme name, skill count, and skill entries.
  """
  # Sort skills alphabetically for deterministic output.
  sortedDocs = sorted(docs, key=lambda d: d.Name)
  # Build the per-skill entries in the sorted order.
  skillEntries = [BuildSkillEntry(doc) for doc in sortedDocs]
  return {
    "Name": themeName,
    "SkillCount": len(sortedDocs),
    "Skills": skillEntries,
  }


def BuildManifest(rootPath: Path) -> dict:
  """
  Build the full manifest dictionary from the skills tree.

  Args:
    rootPath (Path): The skills repository root.

  Returns:
    dict: The manifest with TotalSkills, TotalThemes, and Themes entries.
  """
  # Define the canonical SkillStack-owned themes.
  # Built-in skills outside this scope (ASR, LLM, charts, docx, pdf, pptx, xlsx, etc.) are excluded from the manifest.
  skillStackThemes = {
    "academic-research", "style-integrity", "ml-engineering",
    "data-engineering", "visualization", "writing-citation",
    "ai-text", "ai-output-judgement", "project-tooling",
  }
  # Group parsed skills by their theme, scoped to SkillStack-owned themes.
  byTheme: dict[str, list[SkillDoc]] = {}
  for doc in IterateSkills(rootPath):
    # Skip maestro (it is the orchestrator, not a themed skill) and any non-SkillStack theme.
    if (doc.Theme == "maestro"):
      continue
    if (doc.Theme not in skillStackThemes):
      continue
    byTheme.setdefault(doc.Theme, []).append(doc)
  # Build per-theme entries sorted by theme name.
  themeEntries = [
    BuildThemeEntry(themeName, byTheme[themeName])
    for themeName in sorted(byTheme.keys())
  ]
  # Compute total counts across SkillStack-owned themes only.
  totalSkills = sum(len(docs) for docs in byTheme.values())
  return {
    "TotalSkills": totalSkills,
    "TotalThemes": len(byTheme),
    "Themes": themeEntries,
  }


def SerializeManifest(manifest: dict) -> str:
  """
  Serialize the manifest dictionary into a YAML string.

  Args:
    manifest (dict): The manifest mapping.

  Returns:
    str: A YAML document with a leading comment header.
  """
  # Use a human-friendly YAML style: block layout with sorted keys disabled.
  body = yaml.safe_dump(
    manifest,
    sort_keys=False,
    allow_unicode=True,
    default_flow_style=False,
    width=120,
  )
  # Prepend a header comment identifying the file as auto-generated.
  header = (
    "# Auto-generated by scripts/GenerateManifest.py.\n"
    "# Do not edit by hand; rerun the script to refresh.\n"
  )
  return header + body


def WriteManifest(manifestPath: Path, manifest: dict) -> None:
  """
  Write the manifest YAML document to disk.

  Args:
    manifestPath (Path): Destination file path.
    manifest (dict): The manifest mapping to serialize.
  """
  # Ensure the parent directory exists before opening the file.
  EnsureDir(manifestPath.parent)
  # Serialize the manifest and write it atomically.
  text = SerializeManifest(manifest)
  manifestPath.write_text(text, encoding="utf-8")


def LoadExistingManifest(manifestPath: Path) -> dict | None:
  """
  Load the existing manifest YAML file when present.

  Args:
    manifestPath (Path): Path to the manifest file.

  Returns:
    dict | None: The parsed manifest, or None when the file is missing or
      cannot be parsed.
  """
  # Return None when the manifest file does not yet exist.
  if (not manifestPath.is_file()):
    return None
  # Parse the YAML file, returning None on any parse failure.
  try:
    return yaml.safe_load(manifestPath.read_text(encoding="utf-8"))
  except yaml.YAMLError:
    return None


def ManifestsEqual(left: dict, right: dict) -> bool:
  """
  Compare two manifest dictionaries for structural equality.

  Args:
    left (dict): First manifest.
    right (dict): Second manifest.

  Returns:
    bool: True when the totals and per-theme skill counts match.
  """
  # Compare the top-level totals first as a cheap equality check.
  if (left.get("TotalSkills") != right.get("TotalSkills")):
    return False
  if (left.get("TotalThemes") != right.get("TotalThemes")):
    return False
  # Compare per-theme skill counts as a deeper equality signal.
  leftThemes = {entry.get("Name"): entry.get("SkillCount") for entry in left.get("Themes", [])}
  rightThemes = {entry.get("Name"): entry.get("SkillCount") for entry in right.get("Themes", [])}
  return leftThemes == rightThemes


def ParseArgs(argv: list[str] | None = None) -> argparse.Namespace:
  """Parse command-line arguments."""
  # Build the argument parser with a single check flag.
  parser = argparse.ArgumentParser(
    description="Generate the SkillStack skills.yaml manifest.",
  )
  parser.add_argument(
    "--check",
    action="store_true",
    help="Exit non-zero when the on-disk manifest is stale.",
  )
  parser.add_argument(
    "--root",
    default=str(SkillsRoot()),
    help="Path to the skills repository root (default: auto-detected).",
  )
  parser.add_argument(
    "--output",
    default=str(SkillsRoot() / "skills.yaml"),
    help="Destination manifest path (default: <root>/skills.yaml).",
  )
  return parser.parse_args(argv)


def Main(argv: list[str] | None = None) -> int:
  """
  Entry point for the manifest generator.

  Args:
    argv (list[str] | None): Optional argv override for tests.

  Returns:
    int: Process exit code.
  """
  # Parse arguments and resolve paths.
  args = ParseArgs(argv)
  rootPath = Path(args.root).resolve()
  manifestPath = Path(args.output).resolve()
  # Build the manifest in memory.
  manifest = BuildManifest(rootPath)
  # When --check is set, compare to the on-disk manifest without writing.
  if (args.check):
    existing = LoadExistingManifest(manifestPath)
    if (existing is None):
      # No manifest on disk means it is definitely stale.
      print("manifest: missing (stale)", file=sys.stderr)
      return 1
    if (not ManifestsEqual(existing, manifest)):
      # The on-disk file differs structurally from the rebuilt one.
      print("manifest: stale", file=sys.stderr)
      return 1
    # The on-disk manifest matches the rebuilt one.
    print(f"manifest: fresh ({manifest['TotalSkills']} skills, {manifest['TotalThemes']} themes)")
    return 0
  # Otherwise, write the manifest to disk and print a summary line.
  WriteManifest(manifestPath, manifest)
  print(
    f"wrote {manifestPath} "
    f"({manifest['TotalSkills']} skills, {manifest['TotalThemes']} themes)"
  )
  return 0


if (__name__ == "__main__"):
  # Run the entry point and propagate the exit code.
  sys.exit(Main())
